#!/usr/bin/env python3
"""Make src/desktop_font.c, the desktop's system font, from "Acorn Mode 0
New" by p1.mark (font/acorn-mode-0-new/, from
https://fontstruct.com/fontstructions/show/1281326), licensed under
Creative Commons Attribution-ShareAlike 3.0
(http://creativecommons.org/licenses/by-sa/3.0/) - and so is the table
this makes, an adaptation of it.

The font is the Acorn 8x8 character set drawn on a grid 8 units wide and 16
high - mostly each row doubled, with some refinements at the finer height -
so each glyph is sampled at the centre of each grid cell: 8x16, one byte a
row, the leftmost pixel in bit 7 (the desktop's text is 8x16 pixels, 16x32
OS units).
Characters 32-126 and 160-255 (Latin-1) where the font has them; the rest
are left for libroger's own font (src/font.c).

Usage: mkdesktopfont.py > ../src/desktop_font.c   (needs Pillow)
"""
import os, sys
from PIL import Image, ImageDraw, ImageFont

here = os.path.dirname(os.path.abspath(__file__))
U = 10                                    # pixels a grid unit, rendered at 16 units
font = ImageFont.truetype(os.path.join(here, 'acorn-mode-0-new', 'acorn-mode-0-new.ttf'), 16 * U)

def grid(ch):
    im = Image.new('L', (8 * U, 16 * U), 0)
    ImageDraw.Draw(im).text((0, 0), ch, font=font, fill=255)
    return [[im.getpixel((x * U + U // 2, y * U + U // 2)) > 127 for x in range(8)] for y in range(16)]

missing = grid('')                  # what the font draws for a character it hasn't
rows, have = [], []
for c in range(256):
    cell = None
    if 32 <= c < 127 or c >= 160:
        g = grid(chr(c))
        if g != missing or c == 32:
            cell = [sum(0x80 >> x for x in range(8) if g[r][x]) for r in range(16)]
    have.append(cell is not None)
    rows.append(cell or [0] * 16)

out = sys.stdout
out.write('/* The desktop\'s system font: generated by font/mkdesktopfont.py from\n'
          ' * "Acorn Mode 0 New" by p1.mark (fontstruct.com/fontstructions/show/1281326),\n'
          ' * licensed under CC BY-SA 3.0 (creativecommons.org/licenses/by-sa/3.0/);\n'
          ' * this table, an adaptation of it, is under the same licence. Do not edit. */\n'
          '#include <stdint.h>\n\n'
          'const uint8_t roger_desktop_font[256][16] = {\n')
for c, cell in enumerate(rows):
    label = repr(chr(c)) if 32 <= c < 127 else '%d' % c
    out.write('    {%s},   /* %s */\n' % (', '.join('0x%02x' % b for b in cell), label.replace('*/', '* /')))
out.write('};\n\n/* which characters it has (the rest: src/font.c\'s) */\n'
          'const uint8_t roger_desktop_font_has[256] = {\n')
for k in range(0, 256, 32):
    out.write('    ' + ', '.join('1' if h else '0' for h in have[k:k + 32]) + ',\n')
out.write('};\n')
