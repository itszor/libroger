#!/usr/bin/env python3
"""Make src/font.c, the VDU drivers' 8x8 character set, from the X11
"misc-fixed" 5x8 font (5x8-ISO8859-1.pcf.gz, in the X.Org fonts: "Public
domain font. Share and enjoy."). Each glyph sits in an 8x8 cell, one byte a
row, the leftmost pixel in bit 7 (VDU 23's layout). Characters 32-126 and
160-255 (ISO 8859-1, as RISC OS's Latin1); the rest are blank, for the
program to define with VDU 23.

Usage: mkfont.py [PCF] > ../src/font.c
"""
import gzip, io, sys
from PIL import PcfFontFile

path = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/X11/misc/5x8-ISO8859-1.pcf.gz'
raw = open(path, 'rb').read()
if path.endswith('.gz'):
    raw = gzip.decompress(raw)
font = PcfFontFile.PcfFontFile(io.BytesIO(raw), 'iso8859-1')
rows = []
for c in range(256):
    cell = [0] * 8
    g = font.glyph[c] if (32 <= c < 127 or c >= 160) else None
    if g:
        im = g[3].convert('1')
        # each glyph image is the whole 5x8 cell, top row first (baseline
        # on row 6, descenders on row 7, as in RISC OS's own font): place
        # it from column 1 of the 8x8 cell
        for y in range(im.size[1]):
            for x in range(im.size[0]):
                if im.getpixel((x, y)):
                    r, col = y, 1 + x
                    if 0 <= r < 8 and 0 <= col < 8:
                        cell[r] |= 0x80 >> col
    rows.append(cell)
out = ['/* The VDU drivers\' 8x8 character set: generated by font/mkfont.py from the',
       ' * X11 misc-fixed 5x8 font (public domain). Do not edit. */',
       '#include <stdint.h>', '', 'const uint8_t roger_font[256][8] = {']
for c, cell in enumerate(rows):
    out.append('    {%s},%s' % (', '.join('0x%02x' % b for b in cell),
                                '   /* %s */' % (repr(chr(c)) if 32 <= c < 127 else c) if any(cell) else ''))
out.append('};')
print('\n'.join(out))
