#!/usr/bin/env python3
"""Make src/font.c, the 8x8 character set (the VDU drivers', and the
desktop's drawn double height), from "Acorn Mode 0" by p1.mark
(font/acorn-mode-0/, from https://fontstruct.com/fontstructions/show/1271339),
licensed under Creative Commons Attribution-ShareAlike 3.0
(http://creativecommons.org/licenses/by-sa/3.0/) - and so is the table this
makes, an adaptation of it.

The font draws the Acorn 8x8 character set with each pixel a FontStruct
brick twice as tall as it is wide (mode 0's pixels): 8 bricks across the
advance, 8 down the em (7 above the baseline). Each glyph is sampled at
the centre of each brick: one byte a row, the leftmost pixel in bit 7
(VDU 23's layout). Characters 32-126 and 160-255 (Latin-1, as RISC OS's);
the Latin-1 characters the font hasn't come from the X11 misc-fixed 5x8
font (5x8-ISO8859-1.pcf.gz, in the X.Org fonts: "Public domain font. Share
and enjoy."); the rest are blank, for the program to define with VDU 23.

Usage: mkfont.py [PCF] > ../src/font.c   (needs Pillow)
"""
import gzip, io, os, sys
from PIL import Image, ImageDraw, ImageFont, PcfFontFile

here = os.path.dirname(os.path.abspath(__file__))
U = 20                                    # pixels a brick is wide, rendered at an em of 8 bricks' height
acorn = ImageFont.truetype(os.path.join(here, 'acorn-mode-0', 'acorn-mode-0.ttf'), 16 * U)

def acorn_cell(ch):
    im = Image.new('L', (8 * U, 16 * U), 0)
    ImageDraw.Draw(im).text((0, 0), ch, font=acorn, fill=255)
    return [sum(0x80 >> x for x in range(8) if im.getpixel((x * U + U // 2, y * 2 * U + U)) > 127)
            for y in range(8)]

path = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/X11/misc/5x8-ISO8859-1.pcf.gz'
raw = open(path, 'rb').read()
if path.endswith('.gz'):
    raw = gzip.decompress(raw)
fixed = PcfFontFile.PcfFontFile(io.BytesIO(raw), 'iso8859-1')

def fixed_cell(c):
    # each glyph image is the whole 5x8 cell, top row first (baseline on
    # row 6, descenders on row 7, as in RISC OS's own font): placed from
    # column 1 of the 8x8 cell
    cell = [0] * 8
    g = fixed.glyph[c]
    if g:
        im = g[3].convert('1')
        for y in range(min(8, im.size[1])):
            for x in range(min(7, im.size[0])):
                if im.getpixel((x, y)):
                    cell[y] |= 0x80 >> (1 + x)
    return cell

missing = acorn_cell('')            # what the font draws for a character it hasn't
rows, source = [], []
for c in range(256):
    cell, src = [0] * 8, ''
    if 32 <= c < 127 or c >= 160:
        a = acorn_cell(chr(c))
        if a != missing or c in (32, 160):
            cell = a
        else:
            cell, src = fixed_cell(c), 'misc-fixed'
    rows.append(cell)
    source.append(src)

out = ['/* The 8x8 character set: generated by font/mkfont.py from "Acorn Mode 0"',
       ' * by p1.mark (fontstruct.com/fontstructions/show/1271339), licensed under',
       ' * CC BY-SA 3.0 (creativecommons.org/licenses/by-sa/3.0/) - this table, an',
       ' * adaptation of it, is under the same licence - with the Latin-1 characters',
       ' * it hasn\'t from the X11 misc-fixed 5x8 font (public domain). Do not edit. */',
       '#include <stdint.h>', '', 'const uint8_t roger_font[256][8] = {']
for c, cell in enumerate(rows):
    label = (repr(chr(c)) if 32 <= c < 127 else str(c)).replace('*/', '* /')
    note = ' %s' % source[c] if source[c] else ''
    out.append('    {%s},%s' % (', '.join('0x%02x' % b for b in cell),
                                '   /* %s%s */' % (label, note) if any(cell) else ''))
out.append('};')
print('\n'.join(out))
